    // ==================== LOGIKA CRUD SPRING DAO ====================
    private void loadTableProducts() {
        new Thread(() -> {
            try {
                List<Product> listProduk = productDao.findAll();
                EventQueue.invokeLater(() -> {
                    tableModel.setRowCount(0);
                    for (Product p : listProduk) {
                        tableModel.addRow(new Object[]{
                            p.getId(),
                            p.getName(),
                            p.getCategory(),
                            p.getGrindSize(),
                            p.getWeightGram(),
                            String.format("%.0f", p.getPrice()),
                            p.getStock(),
                            Boolean.TRUE.equals(p.getAvailable()) ? "Tersedia" : "Habis / Nonaktif"
                        });
                    }
                });
            } catch (Exception e) {
                e.printStackTrace();
            }
        }).start();
    }

    private void tambahProduk() {
        if (!validasiInput()) return;

        String nama = txtNamaProduk.getText().trim();
        String kategori = cmbCategory.getSelectedItem().toString();
        String gilingan = cmbGrindSize.getSelectedItem().toString();
        int berat = Integer.parseInt(txtBeratGram.getText().trim());
        double harga = Double.parseDouble(txtHarga.getText().trim());
        int stok = Integer.parseInt(txtStok.getText().trim());
        boolean tersedia = chkAvailable.isSelected();

        new Thread(() -> {
            try {
                Product produkBaru = new Product(nama, kategori, gilingan, berat, harga, stok, tersedia);
                productDao.save(produkBaru);

                EventQueue.invokeLater(() -> {
                    JOptionPane.showMessageDialog(this, "Produk '" + nama + "' (" + gilingan + ") berhasil ditambahkan!");
                    resetForm();
                    loadTableProducts();
                });
            } catch (Exception e) {
                e.printStackTrace();
                EventQueue.invokeLater(() -> JOptionPane.showMessageDialog(this, "Gagal menyimpan: " + e.getMessage()));
            }
        }).start();
    }

    private void updateProduk() {
        if (selectedProductId == null) {
            JOptionPane.showMessageDialog(this, "Klik baris produk pada tabel terlebih dahulu!");
            return;
        }
        if (!validasiInput()) return;

        String nama = txtNamaProduk.getText().trim();
        String kategori = cmbCategory.getSelectedItem().toString();
        String gilingan = cmbGrindSize.getSelectedItem().toString();
        int berat = Integer.parseInt(txtBeratGram.getText().trim());
        double harga = Double.parseDouble(txtHarga.getText().trim());
        int stok = Integer.parseInt(txtStok.getText().trim());
        boolean tersedia = chkAvailable.isSelected();

        new Thread(() -> {
            try {
                Product produkUpdate = new Product(nama, kategori, gilingan, berat, harga, stok, tersedia);
                produkUpdate.setId(selectedProductId);
                productDao.update(produkUpdate);

                EventQueue.invokeLater(() -> {
                    JOptionPane.showMessageDialog(this, "Data produk berhasil diperbarui!");
                    resetForm();
                    loadTableProducts();
                });
            } catch (Exception e) {
                e.printStackTrace();
                EventQueue.invokeLater(() -> JOptionPane.showMessageDialog(this, "Gagal update: " + e.getMessage()));
            }
        }).start();
    }

    private void hapusProduk() {
        if (selectedProductId == null) {
            JOptionPane.showMessageDialog(this, "Pilih produk yang ingin dihapus dari tabel!");
            return;
        }

        int konfirmasi = JOptionPane.showConfirmDialog(this, "Yakin ingin menghapus produk ini?", "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);
        if (konfirmasi != JOptionPane.YES_OPTION) return;

        new Thread(() -> {
            try {
                productDao.delete(selectedProductId);
                EventQueue.invokeLater(() -> {
                    JOptionPane.showMessageDialog(this, "Produk berhasil dihapus!");
                    resetForm();
                    loadTableProducts();
                });
            } catch (Exception e) {
                e.printStackTrace();
            }
        }).start();
    }

    private void pilihBarisTabel() {
        int row = tblProducts.getSelectedRow();
        if (row >= 0) {
            selectedProductId = Integer.parseInt(tblProducts.getValueAt(row, 0).toString());
            txtNamaProduk.setText(tblProducts.getValueAt(row, 1).toString());
            cmbCategory.setSelectedItem(tblProducts.getValueAt(row, 2).toString());
            cmbGrindSize.setSelectedItem(tblProducts.getValueAt(row, 3).toString());
            txtBeratGram.setText(tblProducts.getValueAt(row, 4).toString());
            txtHarga.setText(tblProducts.getValueAt(row, 5).toString());
            txtStok.setText(tblProducts.getValueAt(row, 6).toString());
            chkAvailable.setSelected("Tersedia".equals(tblProducts.getValueAt(row, 7).toString()));
        }
    }

    private boolean validasiInput() {
        if (txtNamaProduk.getText().trim().isEmpty() || txtBeratGram.getText().trim().isEmpty()
                || txtHarga.getText().trim().isEmpty() || txtStok.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Semua kolom wajib diisi!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return false;
        }
        try {
            Integer.parseInt(txtBeratGram.getText().trim());
            Double.parseDouble(txtHarga.getText().trim());
            Integer.parseInt(txtStok.getText().trim());
            return true;
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Berat, Harga, dan Stok harus berupa angka!", "Format Salah", JOptionPane.ERROR_MESSAGE);
            return false;
        }
    }
    
    private void resetForm() {
        selectedProductId = null;
        txtNamaProduk.setText("");
        cmbCategory.setSelectedIndex(0);
        cmbGrindSize.setSelectedIndex(0); // Default kembali ke "Whole Bean (Tanpa Digiling)"
        txtBeratGram.setText("");
        txtHarga.setText("");
        txtStok.setText("");
        chkAvailable.setSelected(true);
        tblProducts.clearSelection();
    }
    private void cetakLaporanStok() {
        new Thread(() -> {
            try {
                javax.sql.DataSource dataSource = main.springContext.getBean(javax.sql.DataSource.class);
                try (java.sql.Connection conn = dataSource.getConnection()) {
                    java.io.InputStream reportStream = getClass().getResourceAsStream("/reports/laporan_stok_produk.jrxml");
                    if (reportStream == null) {
                        EventQueue.invokeLater(() -> JOptionPane.showMessageDialog(this, "File /reports/laporan_stok_produk.jrxml tidak ditemukan!"));
                        return;
                    }
                    net.sf.jasperreports.engine.JasperReport jasperReport = net.sf.jasperreports.engine.JasperCompileManager.compileReport(reportStream);
                    net.sf.jasperreports.engine.JasperPrint jasperPrint = net.sf.jasperreports.engine.JasperFillManager.fillReport(jasperReport, new java.util.HashMap<>(), conn);

                    EventQueue.invokeLater(() -> net.sf.jasperreports.view.JasperViewer.viewReport(jasperPrint, false));
                }
            } catch (Exception e) {
                e.printStackTrace();
                EventQueue.invokeLater(() -> JOptionPane.showMessageDialog(this, "Gagal mencetak laporan: " + e.getMessage()));
            }
        }).start();
    }
